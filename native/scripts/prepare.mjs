// The original store's filters (game-store src/lib/catalog.ts): label ← Steam feature tags.
const FEATURES = [
  ['Single-player', ['Single-player']],
  ['Online multiplayer', ['Online PvP', 'Multi-player']],
  ['Co-op', ['Co-op', 'Online Co-op']],
  ['Cross-play', ['Cross-Platform Multiplayer']],
  ['DualSense features', ['DualSense Controller Support']],
  ['Cloud saves', ['Steam Cloud']],
];
const NON_GENRES = new Set(['Free To Play', 'Early Access']);
const MAX_BYTES = 250;
const MAX_PARAGRAPHS = 6;

const bytes = text => Buffer.byteLength(text);

// Cut at a word; text without spaces (Chinese, Japanese) at a character.
function fit(text) {
  if (bytes(text) <= MAX_BYTES) return text;
  const words = text.split(' ');
  while (words.length > 1 && bytes(`${words.join(' ')}…`) > MAX_BYTES) words.pop();
  if (words.length === 1) return fitBytes(text, MAX_BYTES);
  return `${words.join(' ').replace(/[\s,;:.-]+$/, '')}…`;
}

function chunk(paragraph) {
  const chunks = [];
  for (const sentence of paragraph.split(/(?<=[.!?…])\s+/)) {
    const last = chunks.length - 1;
    if (last >= 0 && bytes(`${chunks[last]} ${sentence}`) <= MAX_BYTES) chunks[last] += ` ${sentence}`;
    else chunks.push(fit(sentence));
  }
  return chunks;
}

const ends = text => /[.!?…"”)]$/.test(text);
const isHeading = line => line.length <= 60 && line === line.toUpperCase() && /\p{L}/u.test(line);

function paragraphs(about) {
  // Store text is cut at a fixed length; drop the unfinished sentence at the end.
  const text = ends(about.trimEnd()) ? about : about.replace(/[^.!?…]*$/, '');
  const lines = [];
  for (const line of text.split('\n').map(line => line.trim()).filter(Boolean)) {
    const previous = lines.at(-1);
    if (previous && !isHeading(previous) && !isHeading(line) && !ends(previous)) lines[lines.length - 1] += ` ${line}`;
    else lines.push(line);
  }
  const result = lines.flatMap(line => (isHeading(line) ? [fit(line)] : chunk(line))).slice(0, MAX_PARAGRAPHS);
  while (result.length > 1 && (isHeading(result.at(-1)) || !ends(result.at(-1)))) result.pop();
  return result;
}

// Steam's 600×900 cover is a third of the bytes of the 2x one and still twice the drawn size; the
// 600×338 screenshot covers the thumbnails.
// Archive.org storage-node addresses (dn710101.ca.archive.org/0/items/…) last only as long as the node
// holds the item; /download/ redirects to wherever it is now.
// Sony's image service resizes to any `w`; like next/image, each box asks for the smallest width bucket
// at least as wide as it draws. A cover draws at most 288 render px wide (the game page's), a gallery
// thumbnail 192: the w=1024 cover (210 KiB median) and the 1920 screenshot used as a thumbnail cost the
// console 13 and 100 times the pixels it shows, decoded one at a time.
const sized = (url, width) => (url.startsWith('https://image.api.playstation.com/')
  ? url.replace(/([?&])w=\d+/, `$1w=${width}`) : url);
const COVER_WIDTH = 384;
const THUMB_WIDTH = 256;
const cover = url => url && sized(url.replace(/library_600x900_2x\.jpg$/, 'library_600x900.jpg')
  .replace(/^https:\/\/[a-z0-9-]+\.(?:[a-z]+\.)?archive\.org\/\d+\/items\//, 'https://archive.org/download/'), COVER_WIDTH);
const thumb = url => sized(url.replace(/\.1920x1080\.jpg/, '.600x338.jpg'), THUMB_WIDTH);
// Hosts that cannot resize go after any copy on Sony's or Steam's CDN (55-61 KiB in under 0.6 s):
// archive.org answers in 2.8 s at the median (a redirect to a storage node, then a 340 KiB PNG) and
// often fails with HTTP 500; spectrumlibrary serves the same square store art as a 1024x1024 PNG of
// 1.1 MiB, and led 13 of the 18 covers on the first grid screen (15 MiB to fetch and decode).
const SLOW = /(?:^|\.)(?:archive\.org|spectrumlibrary\.online)$/;
const slow = url => SLOW.test(new URL(url).hostname);
const coverOrder = urls => [...urls.filter(url => !slow(url)), ...urls.filter(slow)];

// {aspect, dark, blank} per logo URL, measured once by scripts/logos.py and kept between runs;
// entries measured before `blank` existed are measured again.
function logoMetadata(urls) {
  const cache = existsSync(logoCache) ? JSON.parse(readFileSync(logoCache, 'utf8')) : {};
  const missing = urls.filter(url => !(url in cache) || !('blank' in cache[url]));
  if (missing.length) {
    const script = fileURLToPath(new URL('scripts/logos.py', app));
    Object.assign(cache, JSON.parse(execFileSync('python3', [script], {input: JSON.stringify(missing), maxBuffer: 1 << 24})));
    mkdirSync(art, {recursive: true});
    writeFileSync(logoCache, `${JSON.stringify(cache, null, 1)}\n`);
  }
  return cache;
}

// The placeholder colour per cover URL, measured once by scripts/tints.py and kept between runs.
function tints(urls) {
  const cache = existsSync(tintCache) ? JSON.parse(readFileSync(tintCache, 'utf8')) : {};
  const missing = urls.filter(url => !(url in cache));
  if (missing.length) {
    const script = fileURLToPath(new URL('scripts/tints.py', app));
    Object.assign(cache, JSON.parse(execFileSync('python3', [script], {input: JSON.stringify(missing), maxBuffer: 1 << 24})));
    mkdirSync(art, {recursive: true});
    writeFileSync(tintCache, `${JSON.stringify(cache, null, 1)}\n`);
  }
  return cache;
}

const original = JSON.parse(readFileSync(values.catalog, 'utf8'));
const downloadFile = catalogPath('downloads/download-catalog.js');
const downloads = existsSync(downloadFile) ? (await import(pathToFileURL(downloadFile).href)).downloadCatalog : [];
const artworkFile = catalogPath('overrides/artwork-overrides.json');
const artwork = existsSync(artworkFile) ? JSON.parse(readFileSync(artworkFile, 'utf8')).games : {};
const metadataFile = catalogPath('overrides/metadata-overrides.json');
const metadata = existsSync(metadataFile) ? JSON.parse(readFileSync(metadataFile, 'utf8')).games : {};
const auditFile = catalogPath('audits/direct-link-audit/results.json');
const audit = existsSync(auditFile) ? JSON.parse(readFileSync(auditFile, 'utf8')) : [];
// Multipart sets the feed cut short, read from their hosts by scripts/audit-parts.mjs.
const partAuditFile = catalogPath('audits/part-audit/results.json');
const partAudit = existsSync(partAuditFile) ? JSON.parse(readFileSync(partAuditFile, 'utf8')) : [];
if (!partAudit.length) console.warn('No audits/part-audit/results.json in the catalog: multipart sets the feed cut short stay in (run scripts/audit-parts.mjs).');
const rules = sourceRules(audit, partAudit);
const merged = new Map(original.map(game => [game.id, {...game, titleId: game.id, releases: []}]));
for (const game of downloads) {
  const previous = merged.get(game.id);
  if (previous) merged.set(game.id, {...previous, releases: game.releases, images: {...previous.images, cover: previous.images?.cover || game.images?.cover, hero: previous.images?.hero || game.images?.hero}});
  else merged.set(game.id, {...game, slug: game.id.toLowerCase(), shortDescription: game.description,
    about: game.description, developer: '', features: [], metacritic: null, recommendations: 0,
    screenshots: [], images: game.images || {}, sizeGb: game.sizeGb ?? null});
}
// A release's identity: its link, label and platform. Two identical rows of one game get a suffix.
const usedIds = new Set();
function contentId(gameId, release) {
  const link = (release.manifestUrl || release.url || release.browserUrl || '').trim().replace(/^[a-z]+:\/\/[^/?#]+/i, origin => origin.toLowerCase());
  const base = `r${createHash('sha256').update(`${link}\n${release.label || ''}\n${release.platform || ''}`).digest('hex').slice(0, 12)}`;
  let id = base;
  for (let n = 2; usedIds.has(`${gameId}/${id}`); n++) id = `${base}-${n}`;
  usedIds.add(`${gameId}/${id}`);
  return id;
}

// Disabled hosts and dead links leave the catalog, and a game with no source left goes with them: it
// has nothing to offer in the store. A set missing a part counts as no source, and the volumes of one the
// part audit found cut short leave with it.
const removed = {host: 0, dead: 0, locked: 0, incomplete: 0, unproven: 0};
const dropped = [];
const keptUnproven = [];
const sizeMismatches = [];
const futureDates = [];
const today = new Date().toISOString().slice(0, 10);
const catalog = [];
for (const game of merged.values()) {
  const why = new Map(game.releases.map(release => [release, rules.why(release, game.id)]));
  const usable = list => releaseSets(list).some(release => !release.unavailableReason);
  let kept = game.releases.filter(release => !why.get(release));
  // A full last volume alone, with neither the game's size nor the next volume seen elsewhere, is not proof
  // enough to take a game out of the store: its set stays when the game would have nothing else, and the
  // engine says the source is missing parts before decoding if it is.
  const unproven = game.releases.filter(release => !why.get(release) || why.get(release) === 'unproven');
  if (!usable(kept) && usable(unproven)) { kept = unproven; keptUnproven.push(`${game.id} ${game.title}`); }
  for (const release of game.releases) if (!kept.includes(release)) removed[why.get(release)]++;
  const releases = kept.map(release => {
    // `record`: the feed entry it came from, whose rows mirror one upload (failover and sets read it).
    // The id comes from the content, not the feed position, so a re-import keeps saved jobs matched.
    const health = rules.health(release);
    const id = contentId(game.id, release);
    return {...release, id, filename: release.filename.replace(release.id, id), record: release.id.replace(/-\d+$/, ''),
      ...health && {health}};
  });
  const sets = releaseSets(releases);
  if (!sets.some(release => !release.unavailableReason)) {
    if (game.releases.length) dropped.push(`${game.id} ${game.title}`);
    continue;
  }
  // A game without a store size takes its default download's. A store size far from that download's is
  // listed for review, not replaced: compressed (ffpfsc) and padded (exfat) images legitimately differ.
  const preferred = sets[preferredRelease(sets)];
  // Store sizes are decimal GB, as the app shows every size.
  const gb = preferred.sizeBytes / 1e9;
  if (game.sizeGb == null && gb) game.sizeGb = gb;
  else if (gb && Math.max(gb / game.sizeGb, game.sizeGb / gb) > 1.5)
    sizeMismatches.push(`${game.id} ${game.title}: store ${game.sizeGb} GB, default download ${gb.toFixed(2)} GB`);
  const enriched = enrichGame({...game, releases}, metadata[game.id]);
  // A date after the build is a store page for something else (a bundle's expansion, a pre-order):
  // it would lead New releases. It is dropped and listed; fix the entry in metadata-overrides.json.
  if (enriched.releaseDate > today) {
    futureDates.push(`${game.id} ${game.title}: ${enriched.releaseDate}`);
    enriched.releaseDate = '';
  }
  // How its default download is reached, to pick the card among a work's regional entries.
  catalog.push({...enriched, source: {group: describeSource(preferred).group, health: preferred.health}});
}
const logos = logoMetadata(catalog.map(game => game.images.logo).filter(Boolean));
// Covers in the order the app tries them, fastest hosts first.
const coversOf = game => coverOrder((artwork[game.id]?.covers ?? [game.images.cover]).filter(Boolean).map(cover));
const tint = tints(catalog.map(game => coversOf(game)[0]).filter(Boolean));

const records = [];
// Emptied first, so a dropped game's files do not ship in the package.
const releaseDir = new URL('data/releases/', app);
const pageDir = new URL('data/pages/', app);
for (const dir of [releaseDir, pageDir]) { rmSync(dir, {recursive: true, force: true}); mkdirSync(dir, {recursive: true}); }
for (const game of catalog) {
  const covers = coversOf(game);
  // A placeholder logo is dropped, so the app shows the title in text instead.
  const logo = logos[game.images.logo]?.blank ? null : logos[game.images.logo] ?? null;
  // Every entry stays in the app's 32 MiB heap, so it carries only what cards, search and filters read
  // and leaves out empty values; the app derives each entry's release and page files from its id
  // (state/catalog.js). Text and shots only a page or a home row shows load from the page file.
  const data = {
    id: game.id, ...game.titleId !== game.id && {titleId: game.titleId}, title: game.title,
    platform: game.platform || (game.titleId.startsWith('CUSA') ? 'ps4' : 'ps5'),
    ...game.contentKind && game.contentKind !== 'commercial' && {contentKind: game.contentKind},
    // The hosts serving it, for the catalog's host filter: release files load only on the game page.
    providers: [...new Set(game.releases.map(release => providerKey(release.provider)))].sort(),
    // Some source downloads with no browser step (a file link or a host page the app reads), for the
    // catalog's "Direct download" filter.
    ...game.releases.some(release => ['direct', 'page'].includes(describeSource(release).group)) && {direct: true},
    developer: game.developer, publisher: game.publisher,
    releaseDate: game.releaseDate, ...game.releaseDate && {year: Number(game.releaseDate.slice(0, 4))},
    genres: game.genres.filter(genre => !NON_GENRES.has(genre)),
    features: FEATURES.filter(([, tags]) => tags.some(tag => game.features.includes(tag))).map(([label]) => label),
    ...game.metacritic != null && {metacritic: game.metacritic}, recommendations: game.recommendations,
    // Three decimals: formatSize shows a game under 1 GB in MB, where one decimal was off by up to 50 MB.
    ...game.sizeGb != null && {sizeGb: Math.round(game.sizeGb * 1000) / 1000},
    art: {
      cover: covers[0] ?? null,
      ...covers.length > 1 && {coverFallbacks: covers.slice(1)},
      // Drawn under the art until it arrives, as next/image's placeholder.
      ...tint[covers[0]] && {tint: tint[covers[0]]},
      ...game.images.hero && {hero: game.images.hero},
      ...logo && {logo: game.images.logo, logoAspect: logo.aspect, ...logo.dark && {logoDark: true}},
    },
  };
  writeFileSync(new URL(`${encodeURIComponent(game.id)}.json`, pageDir), JSON.stringify({about: paragraphs(game.about),
    shots: game.screenshots.slice(0, 3).map(url => ({url, thumb: thumb(url)})), summary: fit(game.shortDescription)}));
  const releases = JSON.stringify(game.releases);
  if (bytes(releases) > 8*1024*1024) throw new Error(`Too many releases for ${game.id}; split the source catalog.`);
  writeFileSync(new URL(`${encodeURIComponent(game.id)}.json`, releaseDir), releases);
  records.push({data, game});
}

// One card per work and platform. A work's entries share a `work` number (the app groups its PS4 and
// PS5 editions by it); a platform's other entries, mostly other regions, ship as `twins`: the app
// opens them from the card's version sheet, which tells them apart by region and title ID.
const works = new Map();
for (const record of records) {
  const key = workKey(record.data.title);
  works.set(key, [...(works.get(key) ?? []), record]);
}
const twinIds = new Set();
let work = 0;
for (const members of works.values()) {
  if (members.length < 2) continue;
  work++;
  for (const {data} of members) data.work = work;
  for (const platform of new Set(members.map(({data}) => data.platform))) {
    const same = members.filter(({data}) => data.platform === platform);
    if (same.length < 2) continue;
    const [, ...rest] = rankEntries(same.map(({data, game}) => ({...data, source: game.source})));
    for (const {id} of rest) twinIds.add(id);
    for (const {data, game} of same) data.region = regionOf(game.releases);
  }
}
const lines = list => list.map(({data}) => `  ${JSON.stringify(data)},`).join('\n');
const listed = records.filter(({data}) => !twinIds.has(data.id));
const genres = [...new Set(listed.flatMap(({game}) => game.genres.filter(genre => !NON_GENRES.has(genre))))]
  .sort((a, b) => a.localeCompare(b, 'en'));
writeFileSync(output, `${header}
export const games = [
${lines(listed)}
];

export const twins = [
${lines(records.filter(({data}) => twinIds.has(data.id)))}
];

export const genres = ${JSON.stringify(genres)};

export const features = ${JSON.stringify(FEATURES.map(([label]) => label))};
`);
const releasesById = new Map(records.map(({data, game}) => [data.id, game.releases]));
const {errors, warnings} = validateCatalog({games: listed.map(({data}) => data),
  twins: records.filter(({data}) => twinIds.has(data.id)).map(({data}) => data), releasesOf: id => releasesById.get(id), audit, sets: partAudit, today});
writeFileSync(new URL('data/prepare-report.json', app), `${JSON.stringify({removedSources: removed, droppedGames: dropped, keptUnproven, sizeMismatches, futureDates, errors, warnings}, null, 1)}\n`);
console.log(`Wrote data/catalog.js (${listed.length} games; ${twinIds.size} more entries open from their work's version sheet; ${work} works with several entries)`);
console.log(`Left out ${removed.host} sources on disabled hosts, ${removed.locked} behind a password, ${removed.dead} dead links, ${removed.incomplete} volumes of sets cut short and ${removed.unproven} of sets with only a full last volume against them (${keptUnproven.length} games keep theirs, having no other source); dropped ${dropped.length} games with no source left; ${sizeMismatches.length} store sizes differ from the download; ${futureDates.length} future release dates dropped (data/prepare-report.json)`);
console.log(`Validation: ${errors.length} errors, ${warnings.length} warnings (data/prepare-report.json)`);
if (errors.length) {
  for (const line of errors) console.error(`error: ${line}`);
  process.exit(1);
}
